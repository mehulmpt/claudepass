/**
 * Renders the home page for static hosting. Runs at build time (scripts/render-page.ts),
 * so the page is served from Workers static assets: free, and the Worker never runs for it.
 *
 * A static file can't carry a per-request CSP nonce, so every inline <script> and <style>
 * is allowed by its SHA-256 hash instead, and the matching CSP goes into `_headers`.
 */
export async function renderStatic({
	siteKey,
	ladder,
}: {
	siteKey: string
	ladder: number[]
}): Promise<{ html: string; headers: string }> {
	const page = html({ siteKey: escapeHtml(siteKey), ladder })
	const inline = (tag: 'script' | 'style') =>
		[
			...page.matchAll(
				new RegExp(
					`<${tag}(?![^>]*\\bsrc=)[^>]*>([\\s\\S]*?)</${tag}>`,
					'g',
				),
			),
		].map((m) => m[1] ?? '')
	const hashes = async (blocks: string[]) =>
		(await Promise.all(blocks.map(sha256Base64)))
			.map((h) => `'sha256-${h}'`)
			.join(' ')

	const csp = [
		"default-src 'none'",
		`script-src ${await hashes(inline('script'))} https://challenges.cloudflare.com`,
		`style-src ${await hashes(inline('style'))}`,
		'frame-src https://challenges.cloudflare.com',
		"connect-src 'self'",
		"img-src 'self' data:",
		"base-uri 'none'",
		"form-action 'none'",
		"frame-ancestors 'none'",
	].join('; ')

	const headers = `# Generated by scripts/render-page.ts. Do not edit by hand.
/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  Strict-Transport-Security: max-age=31536000
`
	return { html: page, headers }
}

async function sha256Base64(text: string): Promise<string> {
	const digest = await crypto.subtle.digest(
		'SHA-256',
		new TextEncoder().encode(text),
	)
	let bin = ''
	for (const b of new Uint8Array(digest)) bin += String.fromCharCode(b)
	return btoa(bin)
}

